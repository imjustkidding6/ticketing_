    /**
     * @return list<array<string, mixed>>
     */
    public static function all(): array
    {
        return self::AGENTS;
    }

    /**
     * The agents the catalogue places in one department, by code.
     *
     * @return list<array<string, mixed>>
     */
    public static function forDepartmentCode(string $code): array
    {
        return array_values(array_filter(
            self::AGENTS,
            fn (array $agent): bool => $agent['department_code'] === $code,
        ));
    }

    /**
     * The department codes the catalogue expects to find, in first-appearance order.
     *
     * @return list<string>
     */
    public static function departmentCodes(): array
    {
        return array_values(array_unique(array_column(self::AGENTS, 'department_code')));
    }
